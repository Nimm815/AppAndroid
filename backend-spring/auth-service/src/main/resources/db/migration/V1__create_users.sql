CREATE TABLE users (
    UserID INT NOT NULL AUTO_INCREMENT,
    FullName VARCHAR(100) NOT NULL,
    Email VARCHAR(255) NOT NULL,
    PasswordHash VARCHAR(255) NOT NULL,
    Role VARCHAR(120) NOT NULL,
    IsLocked TINYINT(1) NOT NULL DEFAULT 0,
    IsDeleted TINYINT(1) NOT NULL DEFAULT 0,
    UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (UserID),
    CONSTRAINT uq_users_email UNIQUE (Email),
    CONSTRAINT ck_users_name CHECK (CHAR_LENGTH(TRIM(FullName)) > 0),
    CONSTRAINT ck_users_email CHECK (CHAR_LENGTH(TRIM(Email)) > 0),
    CONSTRAINT ck_users_hash CHECK (CHAR_LENGTH(TRIM(PasswordHash)) > 0),
    CONSTRAINT ck_users_role CHECK (CHAR_LENGTH(TRIM(Role)) > 0),
    CONSTRAINT ck_users_locked CHECK (IsLocked IN (0, 1)),
    CONSTRAINT ck_users_deleted CHECK (IsDeleted IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
