CREATE TABLE device_workspaces (
 UserID INT NOT NULL, DeviceID VARCHAR(36) NOT NULL, Revision BIGINT NOT NULL DEFAULT -1,
 Payload JSON NULL, PRIMARY KEY(UserID,DeviceID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE device_records (
 UserID INT NOT NULL, DeviceID VARCHAR(36) NOT NULL, Kind VARCHAR(16) NOT NULL,
 LocalID VARCHAR(100) NOT NULL, RemoteID INT NOT NULL,
 PRIMARY KEY(UserID,DeviceID,Kind,LocalID), INDEX ix_device_remote(Kind,RemoteID),
 FOREIGN KEY(UserID,DeviceID) REFERENCES device_workspaces(UserID,DeviceID) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
